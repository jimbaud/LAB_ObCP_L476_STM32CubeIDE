#!/usr/bin/env python3
"""Compile les dix niveaux décrits en JSON en données C constantes.

    python Tools/build_levels.py

Entrée : Assets/levels.json (11 lignes de tuiles par niveau, une lettre par
         tuile : . vide, # sol, B brique, = plateforme traversable, ^ pics,
         ? bloc à bonus, C bloc solide réservé (il ne s'effondre pas dans
         cette version), ~ eau mortelle ; liste des objets
         [type, variante, x, y, a, b, période] en pixels du monde).
Sortie : Core/Src/content/oa_levels.c (aucun code de jeu, seulement des tableaux).
N'utilise que la bibliothèque standard de Python 3.
SPDX-License-Identifier: MIT
"""
import argparse, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
def compile_levels():
    levels=json.loads((ROOT/'Assets/levels.json').read_text(encoding='utf-8'))
    assert len(levels)==10
    out=['/* Generated by Tools/build_levels.py. SPDX-License-Identifier: MIT */', '#include "oa_engine.h"']
    for i,l in enumerate(levels):
        assert len(l['rows'])==11 and all(len(r)==l['width'] for r in l['rows'])
        assert len(l['objects'])<=128
        chars={'.':0,'#':1,'B':2,'=':3,'^':4,'?':5,'C':6,'~':7}
        tiles=[chars[c] for row in l['rows'] for c in row]
        out+=['static const uint8_t map_%02d[] = {'%i]
        out += [','.join(map(str,tiles[n:n+64]))+',' for n in range(0,len(tiles),64)]
        out+=['};','static const OaObject objects_%02d[] = {'%i]
        out += ['{'+','.join(map(str,o))+'},' for o in l['objects']]
        out+=['};']
    out+=['const OaLevel oa_levels[OA_LEVEL_COUNT] = {']
    for i,l in enumerate(levels):
        out+=['{"%s",%d,%d,32,138,%d,%d,%d,map_%02d,objects_%02d},'%(l['name'],l['width'],l['main_end'],l['exit_x'],l['biome'],len(l['objects']),i,i)]
    out+=['};','']
    (ROOT/'Core/Src/content/oa_levels.c').write_text('\n'.join(out),encoding='utf-8')
    print('10 niveaux compilés ;',sum(l['width']*11 for l in levels),'octets de tuiles : Core/Src/content/oa_levels.c')
if __name__=='__main__':compile_levels()
